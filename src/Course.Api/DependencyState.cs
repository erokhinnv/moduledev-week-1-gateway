namespace Course.Api;

/// <summary>
/// Последнее известное состояние доступности авторитетного хранилища (PostgreSQL).
///
/// Проблема, которую решает этот класс: когда PostgreSQL пропадает (например контейнер
/// остановлен), разрешение его DNS-имени в сети Docker Compose может занимать несколько секунд
/// ещё ДО того, как вообще начнётся попытка подключения. Без этого класса каждый запрос платил бы
/// эту цену заново и мог бы упереться в собственный дедлайн раньше, чем получить осмысленный ответ
/// "503 dependency.unavailable" — вместо этого клиент видел бы менее подходящую ошибку по таймауту.
///
/// Решение: как только первый запрос доказал, что зависимость недоступна, класс "запоминает" это
/// на короткое окно времени, и все последующие запросы в течение этого окна отвечают 503 сразу же,
/// не пытаясь снова ждать медленного разрешения DNS. Окно нарочно короткое: оно истекает само по
/// себе, поэтому восстановление работы не требует ни перезапуска сервиса, ни какого-либо внешнего
/// сигнала "всё снова в порядке" — следующий запрос после истечения окна просто попробует снова.
/// </summary>
public sealed class DependencyState
{
    private static readonly long WindowTicks = TimeSpan.FromSeconds(2).Ticks;

    private long _unavailableUntil;

    /// <summary>true, если недавно (в пределах последнего короткого окна) уже была доказана недоступность зависимости.</summary>
    public bool IsKnownUnavailable => DateTime.UtcNow.Ticks < Interlocked.Read(ref _unavailableUntil);

    /// <summary>Отмечает зависимость как недоступную на ближайшие 2 секунды.</summary>
    public void MarkUnavailable() =>
        Interlocked.Exchange(ref _unavailableUntil, DateTime.UtcNow.Ticks + WindowTicks);

    /// <summary>Немедленно снимает отметку недоступности (вызывается сразу после успешного обращения к базе).</summary>
    public void MarkAvailable() => Interlocked.Exchange(ref _unavailableUntil, 0);
}
