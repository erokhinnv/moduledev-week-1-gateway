-- 022_outbox_retry_budget.sql
-- Тестовый профиль доставки: четыре попытки, включая первую.
--
-- Проблема, которую чиним. Опубликованный профиль проверки задаёт «максимум попыток Outbox — 3»
-- и три задержки: 200, 400 и 800 мс. Строка профиля 'test' в 017_perimeter_core.sql прочитала
-- первое число как общее число HTTP-попыток: max_attempts = 3 при трёх задержках. Третья задержка
-- при этом была недостижима — после третьего отказа доставка уходила в DEAD, не дожидаясь
-- 800 мс, — и таблица противоречила самой себе. Три задержки означают три повтора ПОСЛЕ первой
-- попытки, то есть четыре попытки. Так это читает проверка: provider, недоступный на трёх попытках
-- и вернувшийся к четвёртой, обязан получить платёж, а операция — продолжиться без вмешательства.
-- Так это записано и в контракте следующей недели, уже явно.
--
-- Решение: строка 'test' получает max_attempts = 4, а форма политики закрепляется равенством —
-- задержек ровно на одну меньше, чем попыток. Прежнее ограничение «не меньше» допускало
-- недостижимые задержки, то есть ровно ту рассинхронизацию, которая здесь исправляется. Профиль
-- 'default' (5 попыток, 4 задержки) равенству уже соответствует. fail_outbox берёт задержку по
-- номеру отказа и не меняется.
--
-- Совместимость: доставки, ушедшие в DEAD после третьей попытки на прежнем томе, остаются DEAD.
-- Это зафиксированный технический исход, и переписывать историю задним числом миграция не вправе;
-- поздняя квитанция всё равно подтвердит такую доставку. Стенд недели 3 и так требует чистого тома.

UPDATE delivery.delivery_policy
SET max_attempts = 4
WHERE profile = 'test';

-- Прежнее ограничение снимается по определению, а не по имени: встроенному CHECK на две колонки
-- PostgreSQL даёт имя <таблица>_check, и угадывать его — значит рисковать оставить два ограничения
-- на одну форму, где одно обещает равенство, а другое молча допускает лишние задержки.
DO $$
DECLARE
    v_name text;
BEGIN
    FOR v_name IN
        SELECT c.conname
        FROM pg_catalog.pg_constraint c
        WHERE c.conrelid = 'delivery.delivery_policy'::regclass
          AND c.contype = 'c'
          AND pg_catalog.pg_get_constraintdef(c.oid) ILIKE '%delays_ms%'
    LOOP
        EXECUTE pg_catalog.format('ALTER TABLE delivery.delivery_policy DROP CONSTRAINT %I', v_name);
    END LOOP;
END $$;

ALTER TABLE delivery.delivery_policy
    ADD CONSTRAINT delivery_policy_delays_shape
    CHECK (jsonb_typeof(delays_ms) = 'array' AND jsonb_array_length(delays_ms) = max_attempts - 1);
